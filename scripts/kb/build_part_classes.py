"""Regenerate addon/server/part_classes.json's motor/servo prefixes.

Sources, merged (nothing already in the file is dropped):
  1. the competition manual's legal actuator tables (R501 motors, R502 servos);
  2. the goBILDA catalog, kb/parts/parts.csv, column counts_as: a series prefix
     ("5203-") when every catalog part in that series has the same class,
     otherwise the exact SKU.
The add-in can't import src/, so get_bom and check_robot_rules read this file.

Usage: python3 -I scripts/kb/build_part_classes.py [--check]
  --check  exit 1 if the file is out of date (for CI), without writing.
"""

import csv
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TABLE = REPO / "addon" / "server" / "part_classes.json"
PARTS = REPO / "kb" / "parts" / "parts.csv"

# BIOBUZZ competition manual TU05, R501 Table 12-1 (motors) and R502 Table 12-2
# (example servos). Part-number prefixes, matched case-insensitively.
MANUAL = {
    "motor": [
        "am-3104",  # AndyMark NeveRest (incl. 3104b, 3104c hex)
        "5201-",
        "5202-",
        "5203-",
        "5204-",  # goBILDA Yellow Jacket 520x
        "5000-0002-",  # goBILDA 5000 series / MATRIX
        "NFR-600-100-000",  # NFR Yuksel
        "REV-41-1291",  # REV HD Hex
        "REV-41-1300",  # REV Core Hex
        "75001",  # Studica Maverick
        "SR-MOTOR-DC-01",  # SWYFT Spike
        "739530",
        "39530",  # TETRIX MAX
        "W44260",  # TETRIX TorqueNADO
        "WDM12",  # WATTOS Stingray
    ],
    "servo": [
        "am-4954",  # AndyMark High-Torque
        "Axon MAX",  # Axon MAX+ (named, no part number)
        "DS3235MG",  # DSSERVO 35KG
        "FT5335M-FB",  # FEETECH
        "2000-0025",  # goBILDA Dual Mode
        "REV-41-1097",  # REV Smart Servo
        "75002",  # Studica Multi-Mode Smart Servo
        "P8-100-252-12-R",  # Actuonix micro linear servo
        "HLS12-",  # Hitec linear servo
        "75014",  # Studica linear servo
    ],
}


def _covered(sku: str, prefixes: list[str]) -> bool:
    return any(sku.upper().startswith(p.upper()) for p in prefixes)


def catalog_prefixes(rows: list[dict]) -> dict[str, list[str]]:
    """Safe prefix per motor/servo SKU: a two-segment series every catalog part
    of which has that class, else the exact SKU."""
    out: dict[str, list[str]] = {"motor": [], "servo": []}
    for row in rows:
        cls, sku = row.get("counts_as"), (row.get("sku") or "").strip()
        if cls not in out or not sku:
            continue
        parts = sku.split("-")
        chosen = sku
        # Two segments ("2000-0025-"), never a bare family ("2000-"): the catalog
        # can't promise goBILDA won't reuse a family for other part types.
        for n in (2,):
            if len(parts) <= n:
                break
            prefix = "-".join(parts[:n]) + "-"
            same = [r for r in rows if (r.get("sku") or "").startswith(prefix)]
            if same and all(r.get("counts_as") == cls for r in same):
                chosen = prefix
                break
        if chosen not in out[cls]:
            out[cls].append(chosen)
    return out


def build(current: dict, rows: list[dict]) -> dict:
    data = dict(current)
    cat = catalog_prefixes(rows)
    for cls in ("motor", "servo"):
        merged = list(current.get(cls, []))
        for p in MANUAL[cls] + cat[cls]:
            if not _covered(p, merged):
                merged.append(p)
        # Drop entries made redundant by a shorter prefix in the list.
        merged = [
            p
            for p in merged
            if not any(q != p and p.upper().startswith(q.upper()) for q in merged)
        ]
        data[cls] = sorted(merged, key=str.upper)
    data["_comment"] = (
        "get_bom and check_robot_rules count a component as a class when its part "
        "number or name starts with one of these prefixes (case-insensitive). "
        "Fallback: '_names' matches words in the component name, unless an "
        "'exclude' word is also there. motor/servo lists are regenerated by "
        "scripts/kb/build_part_classes.py from the manual's R501/R502 tables and "
        "the goBILDA catalog (kb/parts/parts.csv counts_as); entries added by hand "
        "are kept."
    )
    order = ["_comment", "motor", "servo"]
    return {k: data[k] for k in order} | {
        k: v for k, v in data.items() if k not in order
    }


def main(argv: list[str]) -> int:
    current = json.loads(TABLE.read_text(encoding="utf-8"))
    with PARTS.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    new = build(current, rows)
    text = json.dumps(new, indent=2, ensure_ascii=False) + "\n"
    if "--check" in argv:
        same = text == TABLE.read_text(encoding="utf-8")
        print(
            "part_classes.json is up to date" if same else "part_classes.json is stale"
        )
        return 0 if same else 1
    TABLE.write_text(text, encoding="utf-8")
    print({k: len(new[k]) for k in ("motor", "servo")})
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
